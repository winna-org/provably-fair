export const getPlinkoResult = (
  seed: Seed,
  args: {
    rows: Pins;
    difficulty: Difficulty;
  },
) => {
  if (args.difficulty === 'extreme') {
    const float = provablyFair(seed).generateFloat();
    const probabilities = EXTREME_POSSIBILITIES[args.rows];

    let cumulativeProbability = 0;
    const result = (() => {
      for (let i = 0; i < probabilities.length; i++) {
        cumulativeProbability += probabilities[i];
        if (float < cumulativeProbability) return i;
      }
      return probabilities.length - 1;
    })();
    return result;
  }

  const result = provablyFair(seed)
    .generateFloats(args.rows)
    .filter((float) => float >= 0.5).length;
  return result;
};
